// Generates src/wire.ts (not checked in) from the protocol schema.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const schemaPath = fileURLToPath(new URL("../../../protocol/schema/lighthouse-protocol-0.4.json", import.meta.url));
const outPath = fileURLToPath(new URL("../src/wire.ts", import.meta.url));

const banner = "// Generated by scripts/wire.mjs from protocol/schema/lighthouse-protocol-0.4.json. Do not edit.";
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const generated = await compile(schema, "Methods", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  format: false,
  strictIndexSignatures: true,
});

writeFileSync(outPath, generated);
