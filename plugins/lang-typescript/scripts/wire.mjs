// Generates src/sdk/wire.ts (not checked in) from the protocol schema.
import { readFileSync, renameSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const schemaPath = fileURLToPath(new URL("../../../protocol/schema/lighthouse-protocol-0.9.json", import.meta.url));
const outPath = fileURLToPath(new URL("../src/sdk/wire.ts", import.meta.url));

const banner = "// Generated by scripts/wire.mjs from protocol/schema/lighthouse-protocol-0.9.json. Do not edit.";
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const generated = await compile(schema, "Methods", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  format: false,
  strictIndexSignatures: true,
});

// Skip an equal file, and replace a different one whole, so a reader of the
// tree never sees a half-written file.
let current = null;
try {
  current = readFileSync(outPath, "utf8");
} catch {}
if (current !== generated) {
  const temp = `${outPath}.${process.pid}.tmp`;
  writeFileSync(temp, generated);
  renameSync(temp, outPath);
}
