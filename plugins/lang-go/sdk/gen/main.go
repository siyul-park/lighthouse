// Command gen writes sdk/wire.go from the protocol schema: the Go structs of
// the messages a provider speaks. Run it with `go generate ./sdk`, or with
// `-check` to fail when the checked-in file is stale.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"unicode"
)

type schema struct {
	Defs map[string]*node `json:"$defs"`
}

// node is the part of a JSON Schema this generator reads.
type node struct {
	Ref                  string           `json:"$ref"`
	Description          string           `json:"description"`
	Type                 json.RawMessage  `json:"type"`
	Enum                 []any            `json:"enum"`
	Const                *string          `json:"const"`
	OneOf                []*node          `json:"oneOf"`
	AnyOf                []*node          `json:"anyOf"`
	Properties           map[string]*node `json:"properties"`
	Required             []string         `json:"required"`
	Items                *node            `json:"items"`
	MinItems             *int             `json:"minItems"`
	MaxItems             *int             `json:"maxItems"`
	AdditionalProperties json.RawMessage  `json:"additionalProperties"`
	Default              json.RawMessage  `json:"default"`
}

type generator struct {
	defs  map[string]*node
	seen  map[string]bool
	order []string
}

// member is a property of a struct, merged over the variants of a choice.
type member struct {
	key      string
	node     *node
	required bool
}

const banner = "// Code generated by sdk/gen from protocol/schema/lighthouse-protocol-0.4.json. DO NOT EDIT."

// roots are the messages a language provider receives and answers; the types
// they reach are generated with them.
var roots = []string{"InitializeParams", "InitializeResult", "IndexParams", "IndexResult"}

// extensions are the Go-only members of a generated struct: state a provider
// hands to the encoder beside the wire fields.
var extensions = map[string]string{
	"IndexResult": "\t// Encoded are fragments that are already JSON, merged in by path when the\n" +
		"\t// result is encoded; Fragments and Encoded never hold the same path.\n" +
		"\tEncoded []EncodedFragment `json:\"-\"`\n",
}

// initialisms are the words Go spells in capitals.
var initialisms = map[string]string{"id": "ID", "uri": "URI", "url": "URL", "ast": "AST", "json": "JSON"}

// UnmarshalJSON reads a boolean schema (`true`: anything) as an empty node.
func (n *node) UnmarshalJSON(data []byte) error {
	var flag bool
	if json.Unmarshal(data, &flag) == nil {
		*n = node{}
		return nil
	}
	type plain node
	return json.Unmarshal(data, (*plain)(n))
}

func (g *generator) render() ([]byte, error) {
	for _, name := range roots {
		g.visit(name)
	}
	var b bytes.Buffer
	b.WriteString(banner + "\n\npackage sdk\n\nimport \"encoding/json\"\n")
	for _, name := range g.order {
		def := g.defs[name]
		if !isStruct(def) {
			continue
		}
		b.WriteString("\n")
		b.WriteString(comment(name+":", def.Description, ""))
		fmt.Fprintf(&b, "type %s struct {\n", name)
		fields, err := g.fields(def)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		b.WriteString(fields)
		b.WriteString(extensions[name])
		b.WriteString("}\n")
	}
	return format.Source(b.Bytes())
}

// visit orders the definitions a node reaches before the node itself.
func (g *generator) visit(name string) {
	if g.seen[name] {
		return
	}
	g.seen[name] = true
	g.collect(g.defs[name])
	g.order = append(g.order, name)
}

func (g *generator) collect(n *node) {
	if n == nil {
		return
	}
	if n.Ref != "" {
		g.visit(refName(n.Ref))
	}
	for _, p := range sortedKeys(n.Properties) {
		g.collect(n.Properties[p])
	}
	for _, list := range [][]*node{n.OneOf, n.AnyOf} {
		for _, m := range list {
			g.collect(m)
		}
	}
	g.collect(n.Items)
	var extra node
	if len(n.AdditionalProperties) > 0 && json.Unmarshal(n.AdditionalProperties, &extra) == nil {
		g.collect(&extra)
	}
}

func (g *generator) fields(def *node) (string, error) {
	var b strings.Builder
	for _, m := range g.members(def) {
		goType, err := g.fieldType(m)
		if err != nil {
			return "", fmt.Errorf("%s: %w", m.key, err)
		}
		description := m.node.Description
		if description == "" && m.node.Ref != "" {
			description = g.defs[refName(m.node.Ref)].Description
		}
		b.WriteString(comment("", description+g.choices(m.node), "\t"))
		tag := m.key
		if !g.alwaysEncoded(m) {
			tag += ",omitempty"
		}
		fmt.Fprintf(&b, "\t%s %s `json:%q`\n", fieldName(m.key), goType, tag)
	}
	return b.String(), nil
}

func (g *generator) members(def *node) []member {
	variants := []*node{def}
	if len(def.Properties) == 0 {
		variants = def.OneOf
	}
	merged := map[string]*member{}
	for _, v := range variants {
		req := map[string]bool{}
		for _, r := range v.Required {
			req[r] = true
		}
		for key, p := range v.Properties {
			m, ok := merged[key]
			if !ok {
				m = &member{key: key, node: p, required: true}
				merged[key] = m
			}
			m.required = m.required && req[key]
		}
	}
	// A property that some variant lacks is optional.
	for _, v := range variants {
		for key, m := range merged {
			if _, ok := v.Properties[key]; !ok {
				m.required = false
			}
		}
	}
	out := make([]member, 0, len(merged))
	for _, key := range sortedKeys(merged) {
		out = append(out, *merged[key])
	}
	return out
}

// choices lists the values of an enumeration a field takes.
func (g *generator) choices(n *node) string {
	target := n
	if n.Ref != "" {
		target = g.defs[refName(n.Ref)]
	}
	values := enumValues(target)
	if len(values) == 0 {
		return ""
	}
	sep := ""
	if n.Description != "" || (n.Ref != "" && target.Description != "") {
		sep = " "
	}
	return sep + "One of " + strings.Join(values, ", ") + "."
}

// alwaysEncoded tells a member that is written even when empty: a required
// one, or one the protocol defaults to a value an absent member would not give
// (a list is `[]`, not `null`).
func (g *generator) alwaysEncoded(m member) bool {
	return m.required || defaulted(m.node)
}

// fieldType is the Go type of a member: a pointer for what has no zero value
// that means "absent" (a struct, a pair, a nullable boolean or number).
func (g *generator) fieldType(m member) (string, error) {
	base, err := g.goType(m.node)
	if err != nil {
		return "", err
	}
	absent := !(m.required || defaulted(m.node)) || nullable(m.node)
	switch {
	case !absent:
		return base, nil
	case strings.HasPrefix(base, "[2]"), g.isStructType(base), base == "bool" && nullable(m.node), base == "int" && nullable(m.node):
		return "*" + base, nil
	}
	return base, nil
}

func (g *generator) isStructType(goType string) bool {
	def, ok := g.defs[goType]
	return ok && isStruct(def)
}

// goType is the Go type a schema node is read into, without the pointer.
func (g *generator) goType(n *node) (string, error) {
	if n.Ref != "" {
		name := refName(n.Ref)
		if isStruct(g.defs[name]) {
			return name, nil
		}
		return g.goType(g.defs[name])
	}
	if len(n.Enum) > 0 || n.Const != nil || len(enumValues(n)) > 0 {
		return "string", nil
	}
	for _, list := range [][]*node{n.AnyOf, n.OneOf} {
		for _, member := range list {
			if len(types(member)) == 1 && types(member)[0] == "null" {
				continue
			}
			return g.goType(member)
		}
	}
	kinds := nonNull(types(n))
	if len(kinds) == 0 {
		return "json.RawMessage", nil
	}
	switch kinds[0] {
	case "string":
		return "string", nil
	case "integer":
		return "int", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "array":
		return g.arrayType(n)
	case "object":
		return g.mapType(n)
	}
	return "", fmt.Errorf("unsupported type %v", kinds)
}

func (g *generator) arrayType(n *node) (string, error) {
	if n.Items == nil {
		return "[]json.RawMessage", nil
	}
	item, err := g.goType(n.Items)
	if err != nil {
		return "", err
	}
	if n.MinItems != nil && n.MaxItems != nil && *n.MinItems == *n.MaxItems && item == "int" {
		return fmt.Sprintf("[%d]uint32", *n.MinItems), nil
	}
	return "[]" + item, nil
}

func (g *generator) mapType(n *node) (string, error) {
	extra := bytes.TrimSpace(n.AdditionalProperties)
	if len(extra) == 0 || string(extra) == "true" || string(extra) == "{}" {
		return "map[string]json.RawMessage", nil
	}
	var value node
	if err := json.Unmarshal(extra, &value); err != nil {
		return "", err
	}
	item, err := g.goType(&value)
	if err != nil {
		return "", err
	}
	return "map[string]" + item, nil
}

func main() {
	schemaPath := flag.String("schema", "../../../protocol/schema/lighthouse-protocol-0.4.json", "the protocol schema")
	out := flag.String("out", "wire.go", "the generated file")
	check := flag.Bool("check", false, "fail when the generated file is stale")
	flag.Parse()
	if err := run(*schemaPath, *out, *check); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(schemaPath, out string, check bool) error {
	raw, err := os.ReadFile(schemaPath)
	if err != nil {
		return err
	}
	var s schema
	if err := json.Unmarshal(raw, &s); err != nil {
		return err
	}
	text, err := (&generator{defs: s.Defs, seen: map[string]bool{}}).render()
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(out)
		if err != nil || !bytes.Equal(current, text) {
			return fmt.Errorf("%s is stale: run go generate ./sdk in plugins/lang-go", out)
		}
		return nil
	}
	return os.WriteFile(out, text, 0o644)
}

func refName(ref string) string {
	return ref[strings.LastIndex(ref, "/")+1:]
}

// isStruct tells a definition that is an object from one that is a name for a
// scalar or a list: an object has properties, or is a choice between objects.
func isStruct(n *node) bool {
	if len(n.Properties) > 0 {
		return true
	}
	return len(n.OneOf) > 0 && n.OneOf[0].Properties != nil
}

func enumValues(n *node) []string {
	var values []string
	for _, v := range n.Enum {
		values = append(values, fmt.Sprintf("%q", v))
	}
	for _, o := range n.OneOf {
		if o.Const != nil {
			values = append(values, fmt.Sprintf("%q", *o.Const))
		}
	}
	return values
}

// defaulted tells a property whose absence the protocol reads as a value.
func defaulted(n *node) bool {
	return len(n.Default) > 0 && string(n.Default) != "null" && !nullable(n)
}

// nullable tells a property that may be null.
func nullable(n *node) bool {
	for _, t := range types(n) {
		if t == "null" {
			return true
		}
	}
	for _, a := range n.AnyOf {
		if nullable(a) {
			return true
		}
	}
	return false
}

func types(n *node) []string {
	if len(n.Type) == 0 {
		return nil
	}
	var one string
	if json.Unmarshal(n.Type, &one) == nil {
		return []string{one}
	}
	var many []string
	_ = json.Unmarshal(n.Type, &many)
	return many
}

func nonNull(kinds []string) []string {
	var out []string
	for _, k := range kinds {
		if k != "null" {
			out = append(out, k)
		}
	}
	return out
}

// fieldName spells a JSON member as an exported Go name.
func fieldName(key string) string {
	var words []string
	var word []rune
	flush := func() {
		if len(word) > 0 {
			words = append(words, string(word))
			word = nil
		}
	}
	for _, r := range key {
		switch {
		case r == '_':
			flush()
		case unicode.IsUpper(r):
			flush()
			word = append(word, unicode.ToLower(r))
		default:
			word = append(word, r)
		}
	}
	flush()
	var b strings.Builder
	for _, w := range words {
		if up, ok := initialisms[w]; ok {
			b.WriteString(up)
			continue
		}
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

// comment writes a doc comment; a type's starts with its name.
func comment(name, description, indent string) string {
	description = strings.TrimSpace(description)
	if description == "" {
		return ""
	}
	lines := strings.Split(description, "\n")
	var b strings.Builder
	for i, line := range lines {
		prefix := ""
		if i == 0 && name != "" {
			prefix = name + " "
		}
		fmt.Fprintf(&b, "%s// %s%s\n", indent, prefix, strings.TrimRight(line, " "))
	}
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
