"""Generates lang_python/wire.py from the protocol schema: TypedDicts of the messages a provider speaks.

Run with `python3 -I scripts/wire.py`, or with `--check` to fail when the checked-in file is stale.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.realpath(__file__))
SCHEMA = os.path.join(HERE, "..", "..", "..", "protocol", "schema", "lighthouse-protocol-0.4.json")
OUT = os.path.join(HERE, "..", "lang_python", "wire.py")
ROOTS = ["InitializeParams", "InitializeResult", "IndexParams", "IndexResult"]
BANNER = '"""Generated by scripts/wire.py from protocol/schema/lighthouse-protocol-0.4.json. Do not edit."""'


def ref_name(ref):
    return ref.rsplit("/", 1)[1]


class Generator:
    def __init__(self, defs):
        self.defs = defs
        self.order = []
        self.seen = set()

    def visit(self, name):
        if name in self.seen:
            return
        self.seen.add(name)
        self.collect(self.defs[name])
        self.order.append(name)

    def collect(self, node):
        if isinstance(node, dict):
            if "$ref" in node:
                self.visit(ref_name(node["$ref"]))
            for value in node.values():
                self.collect(value)
        elif isinstance(node, list):
            for value in node:
                self.collect(value)

    def type_of(self, node):
        if "$ref" in node:
            return ref_name(node["$ref"])
        if "enum" in node:
            return "Literal[%s]" % ", ".join(json.dumps(v) for v in node["enum"])
        if "const" in node:
            return "Literal[%s]" % json.dumps(node["const"])
        for key in ("oneOf", "anyOf"):
            if key in node:
                members = node[key]
                if all("const" in n for n in members):
                    return "Literal[%s]" % ", ".join(json.dumps(n["const"]) for n in members)
                return " | ".join(self.type_of(n) for n in members)
        kind = node.get("type")
        if isinstance(kind, list):
            return " | ".join(self.scalar(k, node) for k in kind)
        if kind is None:
            return "Any"
        return self.scalar(kind, node)

    def scalar(self, kind, node):
        if kind == "string":
            return "str"
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "null":
            return "None"
        if kind == "array":
            return "list[%s]" % self.type_of(node["items"]) if "items" in node else "list[Any]"
        if kind == "object":
            extra = node.get("additionalProperties")
            if isinstance(extra, dict):
                return "dict[str, %s]" % self.type_of(extra)
            return "dict[str, Any]"
        raise ValueError(kind)

    def definition(self, name):
        node = self.defs[name]
        if "properties" in node:
            required = set(node.get("required", []))
            fields = []
            for key in sorted(node["properties"]):
                inner = self.type_of(node["properties"][key])
                fields.append(
                    "        %s: %s," % (json.dumps(key), "Required[%s]" % inner if key in required else inner)
                )
            body = "\n".join(fields)
            return '%s = TypedDict(\n    "%s",\n    {\n%s\n    },\n    total=False,\n)\n' % (name, name, body)
        return "%s = %s\n" % (name, self.type_of(node))

    def render(self):
        for root in ROOTS:
            self.visit(root)
        parts = [BANNER, "", "from typing import Any, Literal, Required, TypedDict", ""]
        for name in self.order:
            parts.append("")
            parts.append(self.definition(name))
        return "\n".join(parts).rstrip("\n") + "\n"


def main(argv):
    with open(SCHEMA, encoding="utf-8") as handle:
        schema = json.load(handle)
    text = Generator(schema["$defs"]).render()
    if "--check" in argv:
        with open(OUT, encoding="utf-8") as handle:
            if handle.read() != text:
                sys.stderr.write("lang_python/wire.py is stale: run python3 -I plugins/lang-python/scripts/wire.py\n")
                return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
