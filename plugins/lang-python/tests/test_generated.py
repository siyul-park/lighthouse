import ast
import unittest

from lang_python.comments import Tokens
from lang_python.extent import Lines
from lang_python.generated import is_generated


def generated(source: str) -> bool:
    return is_generated(ast.parse(source), Tokens(source, Lines(source)))


class GeneratedTests(unittest.TestCase):
    def test_is_generated(self):
        self.assertTrue(generated("# @generated by a tool\nx = 1\n"))
        self.assertTrue(generated("# Code generated by tool. Do not edit.\nx = 1\n"))
        self.assertTrue(generated("# generated, DO NOT EDIT\n\nimport os\n"))

    def test_is_generated_only_above_the_first_statement(self):
        self.assertFalse(generated("x = 1\n# @generated\n"))
        self.assertFalse(generated("# an ordinary comment\nx = 1\n"))
        self.assertFalse(generated(""))


if __name__ == "__main__":
    unittest.main()
