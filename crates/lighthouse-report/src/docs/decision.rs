//! One decision as Markdown, and the pages of the generated docs that hold it.

use std::{collections::BTreeMap, fmt::Write};

use lighthouse_model::squash;
use lighthouse_spec::{Catalog, Decision, Example, ExampleFile, ExampleKind, OptionsSchema};
use similar::TextDiff;

use super::pack;

/// Where the generated decision pages live, relative to the docs root.
pub const DOCS_DIR: &str = "decisions";

pub(super) const NOTICE: &str = "<!-- Generated by `lighthouse docs generate`. Do not edit. -->";

const CONTEXT_LINES: usize = 0;

/// How much of a decision is written.
#[derive(Debug, Clone, Copy)]
pub enum Density<'a> {
    /// One table row of a pack page: the requirement stands in the row when the
    /// decision has nothing beyond it, else the id links to its entry.
    Row,
    /// The entry with its title at heading `level`. `sources` is the directory
    /// the examples' files are linked from; none names the other languages
    /// without links.
    Entry {
        level: usize,
        sources: Option<&'a str>,
    },
}

/// Markdown for every pack, keyed by path relative to the docs root.
pub fn pages(catalog: &Catalog) -> BTreeMap<String, String> {
    catalog
        .packs()
        .iter()
        .map(|pack| {
            (
                format!("{DOCS_DIR}/{}.md", pack.id),
                pack::pack_markdown(pack),
            )
        })
        .collect()
}

/// Where a decision is explained in the generated docs: the pack page and,
/// for a decision that has an entry of its own, the heading anchor. The path
/// is relative to the repository root.
pub fn help_path(decision: &Decision) -> String {
    let page = format!("docs/{DOCS_DIR}/{}.md", decision.pack());
    if is_row(decision) {
        page
    } else {
        format!("{page}#{}", anchor(&decision.title))
    }
}

/// One decision as Markdown, with a trailing newline.
pub fn decision_markdown(decision: &Decision, density: Density) -> String {
    match density {
        Density::Row => row(decision),
        Density::Entry { level, sources } => entry(decision, level, sources),
    }
}

/// A decision enforced by review or not at all, with nothing beyond its
/// requirement.
pub(super) fn is_row(decision: &Decision) -> bool {
    decision
        .check
        .as_ref()
        .is_none_or(|c| !c.kind.deterministic())
        && decision.status.is_default()
        && decision.supersedes.is_empty()
        && decision.consequences.is_none()
        && decision
            .options
            .as_ref()
            .is_none_or(|o| o.properties.is_empty())
        && decision.examples.is_empty()
        && decision.fix.is_none()
        && decision.provenance.is_empty()
}

/// The GitHub heading anchor of `title`.
fn anchor(title: &str) -> String {
    title
        .to_lowercase()
        .chars()
        .filter_map(|c| match c {
            ' ' | '-' => Some('-'),
            c if c.is_alphanumeric() || c == '_' => Some(c),
            _ => None,
        })
        .collect()
}

fn row(decision: &Decision) -> String {
    let (id, requirement) = if is_row(decision) {
        (format!("`{}`", decision.id()), cell(&decision.requirement))
    } else {
        (
            format!("[`{}`](#{})", decision.id(), anchor(&decision.title)),
            String::new(),
        )
    };
    let fix = decision
        .fix
        .as_ref()
        .map_or_else(String::new, |_| decision.fix_safety(None).to_string());
    format!(
        "| {id} | {} | {} | {fix} | {requirement} |\n",
        cell(&decision.title),
        level(decision)
    )
}

fn entry(decision: &Decision, level_of_title: usize, sources: Option<&str>) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "{} {}\n", "#".repeat(level_of_title), decision.title);
    let mut meta = format!(
        "`{}` · {} · {}",
        decision.id(),
        decision.scope.subject,
        level(decision)
    );
    if decision.fix.is_some() {
        let _ = write!(meta, " · fix: {}", decision.fix_safety(None));
    }
    if !decision.languages.is_empty() {
        let listed: Vec<&str> = decision.languages.keys().map(String::as_str).collect();
        let _ = write!(meta, " · {}", listed.join(", "));
    }
    if !decision.status.is_default() {
        let _ = write!(meta, " · {}", decision.status);
    }
    if !decision.supersedes.is_empty() {
        let _ = write!(meta, " · supersedes {}", decision.supersedes.join(", "));
    }
    let _ = writeln!(out, "{meta}\n");
    let _ = writeln!(out, "*{}*\n", squash(&decision.context));
    let _ = writeln!(out, "{}\n", decision.requirement.trim());
    if let Some(consequences) = &decision.consequences {
        let _ = writeln!(out, "Consequences: {}\n", squash(consequences));
    }
    if !decision.provenance.is_empty() {
        let _ = writeln!(
            out,
            "Derived from: {}\n",
            decision.provenance.was_derived_from.join("; ")
        );
    }
    if let Some(options) = decision
        .options
        .as_ref()
        .filter(|o| !o.properties.is_empty())
    {
        options_table(&mut out, decision, options);
    }
    examples(&mut out, &decision.examples, sources);
    out
}

fn options_table(out: &mut String, decision: &Decision, options: &OptionsSchema) {
    let _ = writeln!(out, "| option | default | meaning |");
    let _ = writeln!(out, "| --- | --- | --- |");
    for (name, property) in &options.properties {
        let mut default = format!("`{}`", property.default);
        for (language, spec) in &decision.languages {
            if let Some(value) = spec.options.get(name) {
                let _ = write!(default, "; {language}: `{value}`");
            }
        }
        let _ = writeln!(
            out,
            "| `{name}` | {default} | {} |",
            cell(&property.description)
        );
    }
    out.push('\n');
}

/// The canonical pair, the other languages as links or names.
fn examples(out: &mut String, examples: &[Example], sources: Option<&str>) {
    let Some(invalid) = pick(examples, ExampleKind::Invalid, None) else {
        return;
    };
    let language = &invalid.language;
    if invalid.fixed.is_empty() {
        let valid = pick(examples, ExampleKind::Valid, Some(language));
        example_block(out, invalid, valid);
        if let Some(valid) = valid {
            example_block(out, valid, Some(invalid));
        }
    } else {
        diff_block(out, invalid);
    }
    let mut others: Vec<&str> = Vec::new();
    for example in examples {
        if example.language != *language && !others.contains(&example.language.as_str()) {
            others.push(&example.language);
        }
    }
    if !others.is_empty() {
        let list: Vec<String> = others
            .iter()
            .map(|other| language_links(examples, other, sources))
            .collect();
        let _ = writeln!(out, "Also: {}\n", list.join(", "));
    }
}

/// The canonical example of `kind`, else the first; of `language` when given.
fn pick<'a>(
    examples: &'a [Example],
    kind: ExampleKind,
    language: Option<&str>,
) -> Option<&'a Example> {
    let of_kind = || {
        examples
            .iter()
            .filter(move |e| e.kind == kind && language.is_none_or(|l| e.language == l))
    };
    of_kind().find(|e| e.canonical).or_else(|| of_kind().next())
}

/// The files of `example` that differ from `other`'s: boilerplate both sides
/// share (a manifest, an unchanged source file) is left out.
fn example_block(out: &mut String, example: &Example, other: Option<&Example>) {
    let many = example.files.len() > 1;
    let differs = |file: &&ExampleFile| {
        other.is_none_or(|other| {
            other
                .files
                .iter()
                .all(|o| o.path != file.path || o.text() != file.text())
        })
    };
    let mut files: Vec<&ExampleFile> = example.files.iter().filter(differs).collect();
    if files.is_empty() {
        files = example.files.iter().collect();
    }
    for file in files {
        let label = if many {
            format!("{} {}", example.kind, file.path)
        } else {
            example.kind.to_string()
        };
        let _ = writeln!(
            out,
            "```{} {label}\n{}\n```\n",
            fence_language(&example.language, &file.path),
            file.text().trim_end()
        );
    }
}

/// The language a fence names for a file of an example: the example's own,
/// except for the files that are not written in it (a Go module file, a Cargo
/// manifest, a YAML decision), which a reader and a tool that reads the fence take as what
/// they are.
fn fence_language<'a>(language: &'a str, path: &str) -> &'a str {
    match path.rsplit('/').next().unwrap_or(path) {
        "go.mod" | "go.work" => "gomod",
        "go.sum" => "text",
        "Cargo.lock" => "toml",
        name if name.ends_with(".toml") => "toml",
        name if name.ends_with(".yaml") || name.ends_with(".yml") => "yaml",
        _ => language,
    }
}

fn diff_block(out: &mut String, example: &Example) {
    for fixed in &example.fixed {
        let before = example
            .files
            .iter()
            .find(|f| f.path == fixed.path)
            .map_or("", ExampleFile::text);
        let (before, after) = (with_newline(before), with_newline(fixed.text()));
        let diff = TextDiff::from_lines(&before, &after)
            .unified_diff()
            .context_radius(CONTEXT_LINES)
            .header(&format!("a/{}", fixed.path), &format!("b/{}", fixed.path))
            .to_string();
        let _ = writeln!(out, "```diff\n{}\n```\n", diff.trim_end());
    }
}

/// `go` alone for inline examples or without `sources`, `go ([invalid](..),
/// [valid](..))` for files.
fn language_links(examples: &[Example], language: &str, sources: Option<&str>) -> String {
    let links: Vec<String> = sources
        .into_iter()
        .flat_map(|dir| {
            examples
                .iter()
                .filter(|e| e.language == language)
                .filter_map(move |example| {
                    let source = example.files.iter().find_map(ExampleFile::source)?;
                    Some(format!("[{}]({dir}/{source})", example.kind))
                })
        })
        .collect();
    if links.is_empty() {
        language.to_owned()
    } else {
        format!("{language} ({})", links.join(", "))
    }
}

fn with_newline(text: &str) -> String {
    format!("{}\n", text.trim_end())
}

/// The authored severity and the kind of check: `warn · cel`; `doc` for a
/// decision without a check.
fn level(decision: &Decision) -> String {
    match (&decision.check, decision.severity) {
        (Some(check), Some(severity)) => format!("{severity} · {}", check.kind.name()),
        _ => "doc".to_owned(),
    }
}

/// `text` on one line, safe inside a table cell.
fn cell(text: &str) -> String {
    squash(text).replace('|', "\\|")
}
