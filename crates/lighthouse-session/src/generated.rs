//! What Lighthouse generates from the catalog, the configuration and the
//! crates that define the kinds: the decision docs, the JSON Schema of every
//! kind of document and log record, and the agent skill.

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write,
};

use lighthouse_engine::active;
use lighthouse_report::docs::{DOCS_DIR, fix_operations_markdown, pages};
use lighthouse_resource::{Descriptor, schema_file};
use lighthouse_spec::{Catalog, authored_severity};

use crate::{Result, Session};

/// Marks a skill file as generated: such a file may be rewritten, any other
/// is the user's and is left alone.
pub const SKILL_MARKER: &str = "<!-- generated by lighthouse; do not edit -->";

/// The fixed part of the skill: frontmatter, the loop, the rules of conduct.
const HEAD: &str = include_str!("skill-head.md");

/// How an agent fixes findings, stated once: the skill and the hooks both say it.
pub const AGENT_LOOP: &str = include_str!("agent-loop.md");

/// Every generated page by path under the docs directory: one per pack, and
/// the fix operations.
pub fn bundled_docs() -> BTreeMap<String, String> {
    let mut pages = pages(Catalog::bundled());
    pages.insert(
        format!("{DOCS_DIR}/fix-operations.md"),
        fix_operations_markdown(),
    );
    pages
}

/// Every kind with its schema, by kind name.
pub fn schemas() -> BTreeMap<&'static str, Descriptor> {
    [
        lighthouse_spec::descriptors(),
        lighthouse_rpc::descriptors(),
        lighthouse_store::descriptors(),
    ]
    .into_iter()
    .flatten()
    .map(|d| (d.kind, d))
    .collect()
}

/// The schema of the kind named `kind`, in any letter case.
pub fn schema_of(kind: &str) -> Option<Descriptor> {
    schemas()
        .into_values()
        .find(|d| d.kind.eq_ignore_ascii_case(kind) || schema_file(d.kind) == kind)
}

/// The skill of the project: its catalog layers and its configuration.
pub fn skill_for(session: &Session) -> Result<String> {
    let active = active(&session.config, session.catalog.projects())?;
    Ok(skill(&session.catalog, &active))
}

/// The text of `skills/lighthouse/SKILL.md`: what Lighthouse is for, the loop
/// an agent follows, how to look decisions up, and a digest (id, title, authored severity)
/// of the decisions `active` names. The decision text itself is never copied:
/// the agent reads it from the MCP resources or `lighthouse decision show`.
pub fn skill(catalog: &Catalog, active: &BTreeSet<String>) -> String {
    let mut out = HEAD.replace(
        "{{fix-loop}}",
        &AGENT_LOOP.trim_end().replace('\n', "\n   "),
    );
    let mut by_pack: Vec<(&str, Vec<String>)> = Vec::new();
    for pack in catalog.packs() {
        let lines: Vec<String> = pack
            .sections
            .iter()
            .flat_map(|s| &s.decisions)
            .filter(|d| active.contains(d.id()))
            .map(|d| {
                let level = d.severity.map_or_else(
                    || "doc".to_owned(),
                    |s| authored_severity(s, Some(d)).to_string(),
                );
                let fixable = d.fix.as_ref().map_or(String::new(), |_| {
                    format!(", fixable: {}", d.fix_safety(None))
                });
                format!("- `{}` ({level}{fixable}) {}", d.id(), d.title)
            })
            .collect();
        if !lines.is_empty() {
            by_pack.push((&pack.id, lines));
        }
    }
    let total: usize = by_pack.iter().map(|(_, l)| l.len()).sum();
    let _ = writeln!(out, "\n## Active decisions ({total})\n");
    out.push_str("A decision declares the severity of its findings: `error` is definitive, so it needs no review and only a directive in the code suppresses it; `warn` and `info` are review tasks, and a judgment can hide them whatever level the configuration reports them at. `fixable: safe|unsafe` marks a decision with a fixer and the safety of its fix.\n");
    for (pack, lines) in by_pack {
        let _ = writeln!(out, "\n### {pack}\n");
        for line in lines {
            let _ = writeln!(out, "{line}");
        }
    }
    out
}
