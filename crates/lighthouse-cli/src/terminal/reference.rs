//! The references generated from the definitions: `docs/cli.md` from the clap
//! tree, `docs/mcp.md` from the tool table, and shell completions. Nothing
//! here is written by hand, so the docs cannot drift from the commands.

use std::{fmt::Write, io};

use clap::{Command, CommandFactory};
use clap_complete::Shell;
use lighthouse_cli::surface::tools::{self, Tool};
use lighthouse_resource::schema_file;
use serde_json::Value;

use crate::terminal::command::Cli;

/// The command reference, under the docs directory.
pub const CLI_DOC: &str = "cli.md";
/// The tool reference, under the docs directory.
pub const MCP_DOC: &str = "mcp.md";
/// Width the help is wrapped to in the reference, so that it does not depend
/// on the terminal that generated it.
const WIDTH: usize = 88;

/// Writes the completions of `shell` to stdout.
pub fn completions(shell: Shell) {
    clap_complete::generate(shell, &mut Cli::command(), "lighthouse", &mut io::stdout());
}

/// The reference of every command: its long help, as `--help` prints it.
pub fn cli() -> String {
    let mut root = Cli::command();
    root.build();
    let mut out = String::from(
        "# Command reference\n\n\
         Generated by `lighthouse docs generate` from the command definitions; \
         `lighthouse docs check` fails when it is stale.\n\n\
         Exit codes of every command: 0 success or nothing found, 1 findings over the \
         threshold or a failed test, validation or docs check, 2 usage or runtime error, \
         3 incomplete analysis.\n",
    );
    commands(&root, &mut out);
    out
}

/// One section per command, depth first, in the order `--help` lists them.
/// The global options are described once, in the root's section, not under
/// every command that inherits them.
fn commands(command: &Command, out: &mut String) {
    let inherits = command
        .get_bin_name()
        .is_some_and(|name| name.contains(' '));
    let help = command
        .clone()
        .mut_args(|arg| {
            if inherits && arg.is_global_set() {
                arg.hide(true)
            } else {
                arg
            }
        })
        .term_width(WIDTH)
        .max_term_width(WIDTH)
        .render_long_help();
    let _ = write!(
        out,
        "\n## `{}`\n\n```text\n{}\n```\n",
        command.get_bin_name().unwrap_or_else(|| command.get_name()),
        help.to_string().trim_end()
    );
    for sub in command
        .get_subcommands()
        .filter(|c| c.get_name() != "help" && !c.is_hide_set())
    {
        commands(sub, out);
    }
}

/// The reference of the tools: which command each is the twin of, what it may
/// do to the world, its arguments and its result.
pub fn mcp() -> String {
    let mut out = String::from(
        "# Tool reference\n\n\
         Generated by `lighthouse docs generate` from the tool definitions; \
         `lighthouse docs check` fails when it is stale.\n\n\
         `lighthouse mcp` serves the commands an agent uses in the loop as Model Context \
         Protocol tools. A tool is named by the path of its command joined by `_`, takes \
         the long flags of the command in camelCase and returns the command's \
         `--format json` output as `structuredContent`, with the same JSON in a text block. \
         A failure is a result with `isError: true`; an unknown tool is a protocol error. \
         Housekeeping and setup (`review prune`, `cache clean`, `spec validate`, `schema`, \
         `docs`, `init`, `trust`, `mcp`, `hook`, `completions`) are not tools.\n\n\
         | Tool | Command | Read only | Destructive | Idempotent | Open world | Result |\n\
         | --- | --- | --- | --- | --- | --- | --- |\n",
    );
    for tool in tools::tools() {
        let _ = writeln!(
            out,
            "| [`{name}`](#{name}) | `{command}` | {read} | {destructive} | {idempotent} | {open} | [{kind}](../schema/{file}) |",
            name = tool.name,
            command = command_line(tool),
            read = yes(tool.hints.read_only),
            destructive = yes(tool.hints.destructive),
            idempotent = yes(tool.hints.idempotent),
            open = if tool.hints.open_world {
                "when a remote model is bound"
            } else {
                "no"
            },
            kind = tool.kind,
            file = schema_file(tool.kind),
        );
    }
    for tool in tools::tools() {
        section(tool, &mut out);
    }
    out
}

fn yes(flag: bool) -> &'static str {
    if flag { "yes" } else { "no" }
}

/// The command line a tool is the twin of.
fn command_line(tool: &Tool) -> String {
    let line = format!("lighthouse {}", tool.path.join(" "));
    if tool.name == "fix" {
        format!("{line} --fix")
    } else {
        line
    }
}

fn section(tool: &Tool, out: &mut String) {
    let (title, description) = tool.help();
    let text = if description.starts_with(title.trim_end_matches('.')) {
        description
    } else {
        format!("{title}\n\n{description}")
    };
    let _ = write!(
        out,
        "\n## {name}\n\n{text}\n\nResult: [{kind}](../schema/{file}).\n",
        name = tool.name,
        kind = tool.kind,
        file = schema_file(tool.kind),
    );
    let schema = tool.input_schema();
    let Some(properties) = schema["properties"].as_object().filter(|p| !p.is_empty()) else {
        out.push_str("\nNo arguments.\n");
        return;
    };
    let required = schema["required"].as_array().cloned().unwrap_or_default();
    out.push_str("\n| Argument | Type | Default | Description |\n| --- | --- | --- | --- |\n");
    for (name, property) in properties {
        let _ = writeln!(
            out,
            "| `{name}`{} | {} | {} | {} |",
            if required.iter().any(|r| r == name) {
                " (required)"
            } else {
                ""
            },
            kind_of(property),
            property
                .get("default")
                .map_or_else(String::new, |d| format!("`{d}`")),
            property["description"]
                .as_str()
                .unwrap_or_default()
                .replace('\n', " "),
        );
    }
}

/// The type of a property in one cell: its enum values, or its JSON type.
fn kind_of(property: &Value) -> String {
    if let Some(values) = property["enum"].as_array() {
        return values
            .iter()
            .filter_map(Value::as_str)
            .collect::<Vec<_>>()
            .join(" \\| ");
    }
    if let Some(value) = property["const"].as_str() {
        return value.to_owned();
    }
    if let Some(variants) = property["anyOf"]
        .as_array()
        .or(property["oneOf"].as_array())
    {
        let kinds: Vec<String> = variants.iter().map(kind_of).collect();
        return kinds.join(" \\| ");
    }
    match &property["type"] {
        Value::String(kind) if kind == "array" => format!("{}[]", kind_of(&property["items"])),
        Value::String(kind) => kind.clone(),
        Value::Array(kinds) => kinds
            .iter()
            .filter_map(Value::as_str)
            .collect::<Vec<_>>()
            .join(" \\| "),
        _ => String::new(),
    }
}
